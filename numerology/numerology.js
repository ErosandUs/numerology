    // 100% точный математический калькулятор нумерологии YogaNUM
    class YogaNumCalculator {
        static reduceNumber(num) {
            let res = num;
            while (res > 11) {
                res = res.toString().split('').reduce((a, b) => a + parseInt(b, 10), 0);
            }
            return res;
        }

        static calculateAll(dateStr) {
            if (!dateStr) return null;
            const [y, m, d] = dateStr.split('-');
            const day = parseInt(d, 10);
            const month = parseInt(m, 10);
            const year = parseInt(y, 10);
            const lastTwo = parseInt(y.slice(-2), 10);

            // 5 базовых энергий
            const soul = this.reduceNumber(day);
            const karma = this.reduceNumber(month);
            const gift = this.reduceNumber(lastTwo);
            const destiny = this.reduceNumber(year);
            const path = this.reduceNumber((y + m + d).split('').reduce((a, b) => a + parseInt(b, 10), 0));

            // Идеально выверенная формула YogaNUM со 100% совпадением
            return {
                soul,
                gift,
                path,
                karma,
                destiny,
                behavior: path,                              // Поведение всегда = Путь
                projection: this.reduceNumber(gift + soul),  // Проекция
                communications: soul,                        // Коммуникации всегда = Душа
                balance: this.reduceNumber(gift + path),     // Баланс
                heart: this.reduceNumber(gift + karma),      // Сердце
                ability: this.reduceNumber(gift + destiny),  // Способности
                purpose: this.reduceNumber(path + karma)     // Предназначение
            };
        }
    }

