    // 3. Калькулятор YogaNUM
    class YogaNumCalculator {
        static reduceNumber(num) {
            let res = num;
            while (res > 11) {
                res = res.toString().split('').reduce((a, b) => a + parseInt(b, 10), 0);
            }
            return res;
        }

        static calculateAll(y, m, d) {
            const day = parseInt(d, 10);
            const month = parseInt(m, 10);
            const yearStr = y.toString();
            const year = parseInt(y, 10);
            const lastTwo = parseInt(yearStr.slice(-2), 10);

            const soul = this.reduceNumber(day);
            const karma = this.reduceNumber(month);
            const gift = this.reduceNumber(lastTwo);
            const destiny = this.reduceNumber(year);
            const path = this.reduceNumber((yearStr + m.toString().padStart(2, '0') + d.toString().padStart(2, '0')).split('').reduce((a, b) => a + parseInt(b, 10), 0));

            return {
                soul,
                gift,
                path,
                karma,
                destiny,
                behavior: path,
                projection: this.reduceNumber(gift + soul),
                communications: soul,
                balance: this.reduceNumber(gift + path),
                heart: this.reduceNumber(gift + karma),
                ability: this.reduceNumber(gift + destiny),
                purpose: this.reduceNumber(path + karma)
            };
        }
    }

    function getBehaviorSequences(y, m, d) {
        const dateStr = `${y}${m}${d}`;
        const digits = dateStr.split('').map(Number);
        const rawSum = digits.reduce((a, b) => a + b, 0);

        if (rawSum === 11 || (rawSum > 11 && YogaNumCalculator.reduceNumber(rawSum) === 11)) {
            return ["2-4-1-3"];
        }

        if (rawSum === 19) return ["1-2-3-4", "9-8-7-6"];
        if (rawSum === 28) return ["2-4-1-3", "8-6-9-7"];
        if (rawSum === 37) return ["3-1-4-2", "7-9-6-8"];
        if (rawSum === 46) return ["4-3-2-1", "6-7-8-9"];
        if (rawSum === 10 || (rawSum > 11 && YogaNumCalculator.reduceNumber(rawSum) === 10)) {
            return ["1-2-3-4"];
        }

        if ([5, 50, 55].includes(rawSum)) {
            return Object.keys(behaviorSchemas);
        }

        if (rawSum === 23) return ["1-2-3-4"];
        if (rawSum === 32) return ["4-3-2-1"];
        if (rawSum === 14) return ["3-1-4-2"];
        if (rawSum === 41) return ["2-4-1-3"];

        const reducedPath = YogaNumCalculator.reduceNumber(rawSum);
        const singleDigitMap = {
            1: ["1-2-3-4"],
            2: ["2-4-1-3"],
            3: ["3-1-4-2"],
            4: ["4-3-2-1"],
            6: ["6-7-8-9"],
            7: ["7-9-6-8"],
            8: ["8-6-9-7"],
            9: ["9-8-7-6"]
        };

        return singleDigitMap[reducedPath] || ["1-2-3-4"];
    }

